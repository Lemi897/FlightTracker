/**
 * Resolves an aircraft's country of registration from its ICAO24 hex address
 * ("hex" for local aircraft, "icao24" for global aircraft — same field, different name).
 * Returns null for genuinely unassigned/reserved/special-use blocks, or if the hex
 * string doesn't parse — callers should treat that as "unknown," not an error.
 */
fun countryForIcao24(icao24: String?): CountryInfo? {
    val hex = icao24?.trim()?.removePrefix("0x")?.removePrefix("0X")
    if (hex.isNullOrEmpty()) return null
    val value = hex.toLongOrNull(16) ?: return null

    for (range in ICAO_RANGES) {
        if (value in range.start..range.end) {
            val iso2 = range.iso2 ?: return null
            return CountryInfo(range.country, iso2.uppercase())
        }
    }
    return null
}