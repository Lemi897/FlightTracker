/**
 * Resolves a ship's flag state from its MMSI. Returns null for MIDs that don't
 * appear in the table (coast stations, aids to navigation, malformed MMSIs, or
 * MIDs the ITU hasn't allocated) - callers should treat that as "unknown," not
 * an error.
 */
fun countryForMmsi(mmsi: Long): CountryInfo? {
    val mid = (mmsi / 1_000_000).toInt()
    return MID_TO_COUNTRY[mid]
}