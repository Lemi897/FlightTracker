package com.example.flighttracker

/**
 * A ship's flag state (country of registration), resolved from the first 3 digits
 * of its MMSI - the Maritime Identification Digits (MID), assigned by the ITU.
 *
 * Note: this is the FLAG STATE, not necessarily the ship's "true" origin. Many
 * cargo/tanker vessels register under flags of convenience (Panama, Liberia,
 * Marshall Islands, Malta) regardless of who owns or crews them.
 */
data class CountryInfo(val name: String, val iso2: String)

/**
 * Free, keyless flag CDN (flagcdn.com). Valid widths: 20, 40, 80, 160, 320, 640.
 * 320 is a reasonable size for a modal background; use something smaller (80/160)
 * for a map badge once that's built.
 */
fun flagUrlFor(country: CountryInfo, widthPx: Int = 320): String =
    "https://flagcdn.com/w$widthPx/${country.iso2.lowercase()}.png"

